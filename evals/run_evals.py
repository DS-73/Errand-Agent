"""Run all scenarios and generate the eval table (never hand-written)."""
from __future__ import annotations

import datetime
import os
import sys
import traceback

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

try:
    from .scenarios import SCENARIOS
except ImportError:  # running as a script: python evals/run_evals.py
    from scenarios import SCENARIOS


def main() -> int:
    rows = []
    for scenario in SCENARIOS:
        try:
            actual, notes = scenario.run()
            passed = True
        except AssertionError as exc:
            actual, notes, passed = f"FAILED: {exc}", "", False
        except Exception as exc:  # noqa: BLE001
            actual, notes, passed = f"ERROR: {type(exc).__name__}: {exc}", \
                traceback.format_exc(limit=3), False
        rows.append((scenario, actual, notes, passed))

    passed_count = sum(1 for _, _, _, p in rows if p)
    total = len(rows)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        "# Eval table (generated by `python evals/run_evals.py`)",
        "",
        f"Generated: {stamp}  ",
        f"Result: **{passed_count}/{total} passed**",
        "",
        "| Scenario | Expected | Actual | Pass/Fail | Notes |",
        "|---|---|---|---|---|",
    ]
    for scenario, actual, notes, passed in rows:
        clean_actual = str(actual).replace("|", "\\|").replace("\n", " ")[:240]
        clean_notes = str(notes).replace("|", "\\|").replace("\n", " ")[:160]
        lines.append(
            f"| `{scenario.name}` | {scenario.expected} | {clean_actual} | "
            f"{'PASS' if passed else 'FAIL'} | {clean_notes} |")
    lines.append("")

    with open("evals/EVAL_TABLE.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    for scenario, actual, notes, passed in rows:
        print(f"[{'PASS' if passed else 'FAIL'}] {scenario.name}: {actual}")
    print(f"\n{passed_count}/{total} passed. Wrote evals/EVAL_TABLE.md")
    return 0 if passed_count == total else 1


if __name__ == "__main__":
    sys.exit(main())
